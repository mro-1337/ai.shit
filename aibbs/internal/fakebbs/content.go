func (s *Server) fileList() []*FileEntry {
	s.mu.Lock()
	defer s.mu.Unlock()
	names := make([]string, 0, len(s.files))
	for name := range s.files {
		names = append(names, name)
	}
	// stable order for menus and tests
	for i := 0; i < len(names); i++ {
		for j := i + 1; j < len(names); j++ {
			if names[j] < names[i] {
				names[i], names[j] = names[j], names[i]
			}
		}
	}
	out := make([]*FileEntry, 0, len(names))
	for _, n := range names {
		out = append(out, s.files[n])
	}
	return out
}

func (s *Server) fileByIndex(i int) *FileEntry {
	files := s.fileList()
	if i < 1 || i > len(files) {
		return nil
	}
	return files[i-1]
}

func (s *Server) bump(fn func(*Stats)) {
	s.mu.Lock()
	fn(&s.stats)
	s.mu.Unlock()
}

func (s *Server) addMessage(area, from, subject, body string) *Message {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.nextID++
	m := &Message{ID: s.nextID, Area: area, From: from, To: "All", Subject: subject, Body: body, At: time.Now()}
	s.msgs = append(s.msgs, m)
	s.stats.Posts++
	return m
}

func bannerLine(text string) string {
	return "\x1b[1;36m" + text + "\x1b[0m\r\n"
}

